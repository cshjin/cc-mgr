"""AgyAdapter — ~/.gemini/antigravity-cli/ projects, sessions, and artifacts.

Real on-disk format for Antigravity CLI (agy):
  - Base dir: ~/.gemini/antigravity-cli/ (overridable via AGY_HOME or ANTIGRAVITY_HOME)
  - Sessions:
      * brain/<conversation_id>/.system_generated/logs/transcript.jsonl
        Each line is a JSON record representing a step:
          - USER_INPUT (or source USER_EXPLICIT): user request
          - PLANNER_RESPONSE: model thinking, response text, tool_calls
          - Tool results: GENERIC, VIEW_FILE, RUN_COMMAND, CODE_ACTION,
            LIST_DIRECTORY, GREP_SEARCH, SEARCH_WEB, READ_URL_CONTENT, etc.
          - SYSTEM_MESSAGE: runtime notifications/system messages
      * brain/<conversation_id>/*.md: artifacts generated by the agent during session
        (walkthrough.md, task.md, implementation_plan.md, reports)
      * history.jsonl: lines of {conversationId, workspace, display, timestamp}
      * conversation_summaries.db: SQLite DB with conversation_id, title, preview,
        step_count, last_modified_time, workspace_uris
      * settings.json: CLI settings including model and trustedWorkspaces
      * conversations/<conversation_id>.(db|pb): trajectory databases
"""
from __future__ import annotations

import json

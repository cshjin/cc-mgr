# Step types that carry a tool's output.
_TOOL_STEPS = frozenset({
    "GENERIC", "VIEW_FILE", "RUN_COMMAND", "CODE_ACTION", "LIST_DIRECTORY",
    "GREP_SEARCH", "SEARCH_WEB", "READ_URL_CONTENT", "ASK_QUESTION",
})


def _int(value: Any) -> int:
    try:
        return int(value or 0)
    except (TypeError, ValueError):
        return 0


def _is_user_step(rec: dict[str, Any]) -> bool:
    return rec.get("type") == "USER_INPUT" or rec.get("source") == "USER_EXPLICIT"


def _step_turn(rec: dict[str, Any]) -> dict[str, Any] | None:
    """One transcript step → a normalized turn (None for content-less bookkeeping).

    Shared by list_sessions (counting) and get_conversation (display) so the
    two can't disagree, and so a step type agy adds later is shown with its
    type as a label instead of disappearing.
    """
    stype = rec.get("type") or "?"
    content = rec.get("content") or ""
    thinking = rec.get("thinking") or ""

    def turn(role: str, kind: str, blocks: list[dict[str, Any]], out_tokens: int = 0):
        return {"uuid": str(rec.get("step_index", 0)), "role": role, "kind": kind,
                "timestamp": rec.get("created_at", ""), "model": "", "blocks": blocks,
                "attribution_skill": None, "attribution_plugin": None,
                "output_tokens": out_tokens}

    if _is_user_step(rec):
        text = _clean_user_prompt(content if isinstance(content, str) else "")
        return turn("user", "user", [{"type": "text", "text": text}])
    if stype == "PLANNER_RESPONSE":
        blocks = []
        if isinstance(thinking, str) and thinking.strip():
            blocks.append({"type": "thinking", "text": thinking})
        if isinstance(content, str) and content.strip():
            blocks.append({"type": "text", "text": content})
        for tc in rec.get("tool_calls", []) or []:
            if isinstance(tc, dict):
                blocks.append({"type": "tool_use", "name": tc.get("name", "?"),
                               "input": _clean_args(tc.get("args", {}))})
        if not blocks:
            return None
        out_tokens = _int(rec.get("output_tokens")) or (
            len(content) // 4 if isinstance(content, str) else 0)
        return turn("assistant", "assistant", blocks, out_tokens)
    if stype in _TOOL_STEPS:
        text = content if isinstance(content, str) else json.dumps(content, ensure_ascii=False)
        return turn("user", "tool", [{"type": "tool_result", "text": text}])
    if stype == "CHECKPOINT":
        text = content if isinstance(content, str) else ""
        return turn("system", "system", [{"type": "text", "text": f"[checkpoint]\n{text}".rstrip()}])
    if stype == "ERROR_MESSAGE":
        err = rec.get("error") or content
        return turn("system", "system", [{"type": "text", "text": f"[error] {err}"}]) if err else None
    text = content if isinstance(content, str) else json.dumps(content, ensure_ascii=False)
    if not text.strip():
        return None  # SYSTEM_MESSAGE without text, CONVERSATION_HISTORY, …
    label = "" if stype == "SYSTEM_MESSAGE" else f"[{stype}] "
    return turn("system", "system", [{"type": "text", "text": label + text}])


def agy_home() -> Path:
    for var in ("AGY_HOME", "ANTIGRAVITY_HOME", "ANTIGRAVITY_CLI_HOME"):
        env = os.environ.get(var)
        if env:
            return Path(env).expanduser()
    default = Path.home() / ".gemini" / "antigravity-cli"
    if not default.exists() and (Path.home() / ".antigravity").exists():
        return Path.home() / ".antigravity"
    return default


def _clean_user_prompt(text: str) -> str:
    if not text:
        return ""
    m = re.search(r"<USER_REQUEST>\s*(.*?)\s*</USER_REQUEST>", text, re.DOTALL)
    if m:
        return m.group(1).strip()
    cleaned = re.sub(r"<ADDITIONAL_METADATA>.*?</ADDITIONAL_METADATA>", "", text, flags=re.DOTALL)
    cleaned = re.sub(r"<USER_SETTINGS_CHANGE>.*?</USER_SETTINGS_CHANGE>", "", cleaned, flags=re.DOTALL)
    return cleaned.strip() or text.strip()


def _clean_args(args: Any) -> Any:
    if isinstance(args, dict):
        cleaned = {}
        for k, v in args.items():
            if isinstance(v, str):
                v_str = v.strip()
                if (v_str.startswith('"') and v_str.endswith('"')) or (
                    v_str.startswith("'") and v_str.endswith("'")
                ):
                    try:
                        v = json.loads(v_str)
                    except Exception:
                        v = v_str[1:-1]
            cleaned[k] = v
        return cleaned
    return args


def _extract_ws_from_transcript(path: Path) -> str:
    """Peek the head of transcript to deduce working directory if metadata missing."""
    if not path.is_file():
        return ""
    try:
        with path.open("r", encoding="utf-8", errors="replace") as f:
            for i, line in enumerate(f):
                if i > 25:
                    break
                line = line.strip()
                if not line:
                    continue
                try:
                    d = json.loads(line)
                except json.JSONDecodeError:
                    continue
                content = d.get("content") or ""
                if isinstance(content, str):
                    m = re.search(r"Your working directory is\s+([^\s\n]+)", content)
                    if m:
                        p = m.group(1).rstrip("/")
                        if "/.agents" in p:
                            p = p.split("/.agents")[0]
                        return p
                    m2 = re.search(r"Project working directory:\s+([^\s\n]+)", content)
                    if m2:
                        p = m2.group(1).rstrip("/")
                        if "/.agents" in p:
                            p = p.split("/.agents")[0]
                        return p
                for tc in d.get("tool_calls", []) or []:
                    args = tc.get("args") or {}
                    for k in ("Cwd", "DirectoryPath", "SearchDirectory"):
                        if k in args and isinstance(args[k], str):
                            v = args[k].strip('"').strip("'")
                            if v.startswith("/"):
                                if "/.agents" in v:
                                    v = v.split("/.agents")[0]
                                return v
    except OSError:
        pass
    return ""


def _scan_signature(home: Path) -> tuple:
    def sig(p: Path):
        try:
            st = p.stat()
            return (st.st_mtime_ns, st.st_size)
        except OSError:
            return None
    db = home / "conversation_summaries.db"
    return (sig(home / "brain"), sig(home / "history.jsonl"), sig(db),
            sig(db.with_name(db.name + "-wal")))


# One request asks for the scan several times (_project_cwd, list_sessions, …).
# Reuse it briefly; any added/removed conversation or metadata change
# invalidates it immediately via the signature.
_SCAN_TTL = 3.0
_scan_cache: dict[str, tuple[float, tuple, Any]] = {}


def _scan_sessions(home: Path) -> tuple[dict[str, list[dict[str, Any]]], dict[str, dict[str, Any]]]:
    """Scan all AGY sessions and group them by project cwd (cached briefly).

    Returns:
      (projects_map, sessions_by_id)
    """
    key = str(home)
    sig = _scan_signature(home)
    now = time.monotonic()
    hit = _scan_cache.get(key)
    if hit and hit[1] == sig and now - hit[0] < _SCAN_TTL:
        return hit[2]
    result = _scan_sessions_uncached(home)
    _scan_cache[key] = (now, sig, result)
    return result


def _scan_sessions_uncached(home: Path) -> tuple[dict[str, list[dict[str, Any]]], dict[str, dict[str, Any]]]:
    brain = home / "brain"
    if not brain.is_dir():
        return {}, {}

    # 1. Read history.jsonl
    history_map: dict[str, str] = {}
    h_file = home / "history.jsonl"
    if h_file.is_file():
        for rec in iter_jsonl(h_file):
            cid = rec.get("conversationId")
            ws = rec.get("workspace")
            if cid and ws and cid not in history_map:
                history_map[cid] = ws

    # 2. Read conversation_summaries.db
    db_map: dict[str, str] = {}
    parent_map: dict[str, str] = {}
    titles_map: dict[str, str] = {}
    preview_map: dict[str, str] = {}
    db_file = home / "conversation_summaries.db"
    if db_file.is_file():
        try:
            conn = connect_sqlite_ro(db_file)
            cursor = conn.execute(
                "SELECT conversation_id, title, preview, workspace_uris, parent_conversation_id "
                "FROM conversation_summaries"
            )
            for cid, title, preview, w_uris, pid in cursor.fetchall():
                if title:
                    titles_map[cid] = title
                if preview:
                    preview_map[cid] = preview
                if pid:
                    parent_map[cid] = pid
                try:
                    uris = json.loads(w_uris) if w_uris else []
                    if uris and isinstance(uris, list):
                        p = uris[0]
                        if p.startswith("file://"):
                            p = p[7:]
                        db_map[cid] = p
                except Exception:
                    pass
            conn.close()
        except Exception:
            pass

    projects_map: dict[str, list[dict[str, Any]]] = {}
    sessions_by_id: dict[str, dict[str, Any]] = {}

    for d in brain.iterdir():
        if not d.is_dir():
            continue
        cid = d.name
        tfile = d / ".system_generated" / "logs" / "transcript.jsonl"
        if not tfile.is_file():
            continue

        # Resolve workspace
        ws = db_map.get(cid) or history_map.get(cid)
        if not ws and parent_map.get(cid):
            parent = parent_map[cid]
            ws = db_map.get(parent) or history_map.get(parent)
        if not ws:
            ws = _extract_ws_from_transcript(tfile)
        if not ws:
            ws = str(Path.home())

        st = tfile.stat()
        info = {
            "session_id": cid,
            "cwd": ws,
            "transcript_path": tfile,
            "mtime": st.st_mtime,
            "size_bytes": st.st_size,
            "title": titles_map.get(cid, ""),
            "preview": preview_map.get(cid, ""),
            "parent_id": parent_map.get(cid, ""),
        }
        sessions_by_id[cid] = info
        projects_map.setdefault(ws, []).append(info)

    return projects_map, sessions_by_id


class AgyAdapter(AgentAdapter):
    capabilities = Capabilities(
        agent_id="agy",
        label="Antigravity (agy)",
        doc_filename="GEMINI.md",
        has_memory=True,
        has_tasks=False,
        can_edit_doc=True,
        can_delete=True,
        can_export=True,
        delete_note=("A soft delete moves brain/<id>/ and the session's conversations/ and "
                     "annotations/ files to .cc_mgr_trash/, with its conversation_summaries "
                     "row saved there (reversible)."),
    )

    def _home(self) -> Path:
        return agy_home()

    def has_data(self) -> bool:
        brain = self._home() / "brain"
        return brain.is_dir() and any(brain.iterdir())

    def _project_cwd(self, project: str) -> str:
        """Resolve a project name back to its working directory.

        Unknown names resolve to "" (never a guessed path that a doc save
        could write into).
        """
        projects, _ = _scan_sessions(self._home())
        names = project_names(projects)
        return next((cwd for cwd in projects if names[cwd] == project), "")

    def list_projects(self) -> list[dict[str, Any]]:
        home = self._home()
        projects, _ = _scan_sessions(home)
        names = project_names(projects)
        out: list[dict[str, Any]] = []

        for cwd, sessions in projects.items():
            if not sessions:
                continue
            mtimes = [s["mtime"] for s in sessions]
            name = names[cwd]
            # Check if memory/artifacts exist
            brain = home / "brain"
            has_mem = False
            for s in sessions:
                sid = s["session_id"]
                s_brain = brain / sid
                if s_brain.is_dir():
                    for f in s_brain.glob("*.md"):
                        if not f.name.endswith(".metadata.json"):
                            has_mem = True
                            break
                if has_mem:
                    break
            if not has_mem and cwd:
                has_mem = (Path(cwd) / ".agents").is_dir() or (Path(cwd) / "memory").is_dir()

            has_doc = False
            if cwd:
                has_doc = (Path(cwd) / "GEMINI.md").is_file() or (Path(cwd) / "AGENTS.md").is_file()

            out.append({
                "name": name,
                "display_path": cwd,
                "cwd": cwd,
                # subagent conversations are listed under their parent, not counted
                "session_count": sum(1 for s in sessions if not s.get("parent_id")),
                "has_memory": has_mem,
                "has_claude_md": has_doc,
                "open_tasks": 0,
                "total_tasks": 0,
                "git": read_git_info(cwd),
                "mtime": max(mtimes),
            })

        out.sort(key=lambda p: p["mtime"], reverse=True)
        return out

    def list_sessions(self, project: str) -> list[SessionSummary]:
        home = self._home()
        projects, _ = _scan_sessions(home)
        cwd = self._project_cwd(project)
        sessions = projects.get(cwd, [])

        git = read_git_info(cwd)
        branch = git["branch"] if git else ""
        out: list[SessionSummary] = []

        for s_info in sessions:
            cid = s_info["session_id"]
            tfile: Path = s_info["transcript_path"]
            try:
                fst = tfile.stat()  # fresh: the scan may be a few seconds old
            except OSError:
                continue

            first_prompt = ""
            last_prompt = s_info.get("preview", "")
            user_turns = 0
            asst_turns = 0
            total_turns = 0
            chars_since_checkpoint = 0
            asst_chars = 0
            last_ctx = peak_ctx = real_output = 0

            for rec in iter_jsonl(tfile):
                stype = rec.get("type")
                content = rec.get("content") or ""
                thinking = rec.get("thinking") or ""
                if stype == "CHECKPOINT":
                    chars_since_checkpoint = 0  # a compaction resets the live context
                if isinstance(content, str):
                    chars_since_checkpoint += len(content)
                if isinstance(thinking, str):
                    chars_since_checkpoint += len(thinking)
                if "input_tokens" in rec:  # real usage, recorded on PLANNER_RESPONSE
                    ctx = (_int(rec.get("input_tokens")) + _int(rec.get("cache_read_tokens"))
                           + _int(rec.get("output_tokens")))
                    if ctx:
                        last_ctx = ctx
                        peak_ctx = max(peak_ctx, ctx)
                    real_output += _int(rec.get("output_tokens"))

                turn = _step_turn(rec)
                if turn is None:
                    continue
                total_turns += 1
                if turn["kind"] == "user":
                    user_turns += 1
                    clean = turn["blocks"][0]["text"]
                    if clean:
                        if not first_prompt:
                            first_prompt = clean[:500]
                        last_prompt = clean[:500]
                elif turn["kind"] == "assistant":
                    asst_turns += 1
                    if isinstance(content, str):
                        asst_chars += len(content)

            # Real token counts when agy recorded them; otherwise a rough estimate
            # of the live context (text since the last compaction / 4). No tier is
            # claimed: agy doesn't record which model a session used.
            est_context = last_ctx or chars_since_checkpoint // 4
            est_output = real_output or asst_chars // 4
            win = context_window("", max(peak_ctx, est_context))

            # Check if this session has artifacts
            s_brain = home / "brain" / cid
            has_mem = False
            if s_brain.is_dir():
                for f in s_brain.glob("*.md"):
                    if not f.name.endswith(".metadata.json"):
                        has_mem = True
                        break

            summ = SessionSummary(
                session_id=cid,
                project=project,
                file=str(tfile),
                size_bytes=fst.st_size,
                mtime=fst.st_mtime,
                first_prompt=first_prompt,
                last_prompt=last_prompt,
                message_count=total_turns,
                user_turns=user_turns,
                assistant_turns=asst_turns,
                context_tokens=est_context,
                context_limit=win["limit"],
                context_limit_known=win["known"],
                total_output_tokens=est_output,
                model="",  # agy doesn't record a per-session model
                git_branch=branch,
                cwd=cwd,
                has_memory=has_mem,
                agent="agy",
                title=s_info.get("title", ""),
                parent_id=s_info.get("parent_id", ""),
            )
            out.append(summ)

        out.sort(key=lambda s: s.mtime, reverse=True)
        return out

    def get_conversation(self, project: str, session_id: str,
                         offset: int = 0, limit: int | None = None) -> dict[str, Any]:
        if not is_safe_id(session_id):
            return {"total": 0, "offset": offset, "limit": limit, "turns": []}
        tfile = (safe_join(self._home() / "brain", session_id)
                 / ".system_generated" / "logs" / "transcript.jsonl")
        if not tfile.is_file():
            return {"total": 0, "offset": offset, "limit": limit, "turns": []}

        turns = [t for t in (_step_turn(rec) for rec in iter_jsonl(tfile)) if t]

        total = len(turns)
        end = total if limit is None else min(total, offset + limit)
        return {
            "total": total,
            "offset": offset,
            "limit": limit,
            "turns": turns[offset:end],
        }

    def iter_turns(self, project: str, session_id: str) -> Iterator[dict[str, Any]]:
        conv = self.get_conversation(project, session_id, offset=0, limit=None)
        for seq, turn in enumerate(conv["turns"]):
            yield {
                "seq": seq,
                "role": turn["role"],
                "kind": turn["kind"],
                "timestamp": turn.get("timestamp", ""),
                "blocks": turn["blocks"],
            }

    def get_doc(self, project: str) -> dict[str, Any]:
        cwd = self._project_cwd(project)
        if not cwd:
            return {"exists": False, "path": "", "content": "", "cwd": ""}
        for fname in ("GEMINI.md", "AGENTS.md"):
            p = Path(cwd) / fname
            if p.is_file():
                return read_doc_file(cwd, fname)
        return read_doc_file(cwd, "GEMINI.md")

    def save_doc(self, project: str, content: str, expect_cwd: str | None = None) -> Path:
        cwd = self._project_cwd(project)
        check_cwd(cwd, expect_cwd)
        if not cwd:
            raise FileNotFoundError("no working directory known for this project")
        # If AGENTS.md exists and GEMINI.md doesn't, write to AGENTS.md
        if (Path(cwd) / "AGENTS.md").is_file() and not (Path(cwd) / "GEMINI.md").is_file():
            return save_doc_file(cwd, "AGENTS.md", content, expect_cwd)
        return save_doc_file(cwd, "GEMINI.md", content, expect_cwd)

    def get_memory(self, project: str) -> dict[str, Any]:
        cwd = self._project_cwd(project)
        home = self._home()
        projects, _ = _scan_sessions(home)
        sessions = projects.get(cwd, [])

        files: list[dict[str, Any]] = []
        seen_paths: set[str] = set()

        # 1. Collect session artifacts from brain/<cid>/*.md
        brain = home / "brain"
        for s in sessions:
            cid = s["session_id"]
            s_brain = brain / cid
            if s_brain.is_dir():
                for f in sorted(s_brain.glob("*.md")):
                    if f.name.endswith(".metadata.json"):
                        continue
                    p_str = str(f)
                    if p_str in seen_paths:
                        continue
                    seen_paths.add(p_str)
                    files.append({
                        "name": f"{cid[:8]}_{f.name}",
                        "path": p_str,
                        "content": f.read_text(encoding="utf-8", errors="replace"),
                    })

        # 2. Collect rules or memory files from <cwd>/.agents/ or <cwd>/memory/
        if cwd:
            for base_dir in (Path(cwd) / ".agents" / "rules", Path(cwd) / ".agents", Path(cwd) / "memory"):
                if base_dir.is_dir():
                    for f in sorted(base_dir.glob("*.md")):
                        p_str = str(f)
                        if p_str in seen_paths:
                            continue
                        seen_paths.add(p_str)
                        files.append({
                            "name": f.name,
                            "path": p_str,
                            "content": f.read_text(encoding="utf-8", errors="replace"),
                        })

        index_lines = ["# Antigravity Project Artifacts & Memory", ""]
        if files:
            index_lines.append(f"Found {len(files)} artifact(s) and document(s):")
            index_lines.append("")
            for f in files:
                index_lines.append(f"- **{f['name']}** (`{f['path']}`)")
        else:
            index_lines.append("_No artifacts or memory files found for this project._")

        index_content = "\n".join(index_lines)
        return {
            "index": index_content,
            "index_path": str(Path(cwd) / ".agents") if cwd else "",
            "dir": cwd,
            "files": files,
        }

    def save_memory_file(self, project: str, name: str, content: str,
                         expect_dir: str | None = None) -> Path:
        if "/" in name or "\\" in name or name in ("", ".", ".."):
            raise ValueError("invalid memory file name")
        if not name.endswith(".md"):
            raise ValueError("memory files must end in .md")
        cwd = self._project_cwd(project)
        check_cwd(cwd, expect_dir)  # get_memory reports the cwd as its "dir"
        if not cwd:
            raise FileNotFoundError("no working directory known for this project")
        # Anchored at the project cwd: a symlinked .agents/ or rules file can't
        # point the write elsewhere.
        out = safe_join(Path(cwd), ".agents", "rules", name)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(content, encoding="utf-8")
        return out

    def export_session_markdown(self, project: str, session_id: str) -> str:
        self._transcript(session_id)  # unknown sessions are a 404, not an empty document
        data = self.get_conversation(project, session_id, offset=0, limit=None)
        cwd = self._project_cwd(project)
        lines = [f"# Session {session_id}", f"_Project: {project}_", f"_Working Directory: {cwd}_", ""]
        for t in data["turns"]:
            role = t["kind"]
            ts = t.get("timestamp") or ""
            header = f"## {role}"
            if ts:
                header += f"  ·  {ts}"
            lines.append(header)
            for b in t["blocks"]:
                bt = b["type"]
                if bt == "text":
                    lines.append(b["text"])
                elif bt == "thinking":
                    lines.append(f"> _(thinking)_\n>\n> " + b["text"].replace("\n", "\n> "))
                elif bt == "tool_use":
                    inp = json.dumps(b["input"], indent=2, ensure_ascii=False)
                    lines.append(f"**→ tool: {b['name']}**\n\n```json\n{inp}\n```")
                elif bt == "tool_result":
                    txt = b.get("text", "")
                    lines.append(f"**tool result**\n\n```\n{txt}\n```")
                lines.append("")
            lines.append("")
        return "\n".join(lines)

    def _transcript(self, session_id: str) -> Path:
        """The session's transcript; FileNotFoundError if it isn't a session."""
        if not is_safe_id(session_id):
            raise ValueError("invalid session id")
        path = (safe_join(self._home() / "brain", session_id)
                / ".system_generated" / "logs" / "transcript.jsonl")
        if not path.is_file():
            raise FileNotFoundError(f"session {session_id} not found")
        return path

    def export_session_to_file(self, project: str, session_id: str, out_dir: Path | None = None) -> Path:
        self._transcript(session_id)
        if out_dir is None:
            out_dir = default_export_dir(project)
        private_mkdir(out_dir)
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        out_path = out_dir / f"{session_id}.{stamp}.md"
        return write_private(out_path, self.export_session_markdown(project, session_id))

    def save_session_as_memory(self, project: str, session_id: str) -> Path:
        """Distill an AGY session into a summary markdown file in project memory."""
        cwd = self._project_cwd(project)
        if not cwd:
            raise FileNotFoundError("no working directory known for this project")
        summ = None
        for s in self.list_sessions(project):
            if s.session_id == session_id:
                summ = s
                break
        if summ is None:
            raise FileNotFoundError(f"session {session_id} not found in {project}")

        short = session_id[:8]
        body = [
            "---",
            f"name: session-{short}",
            f"description: archived summary of Antigravity session {short} in {project}",
            "metadata:",
            "  type: reference",
            "---",
            "",
            f"Archived summary of Antigravity session `{session_id}` (project `{project}`), saved before deletion via cc_mgr.",
            "",
            f"- **Turns:** {summ.message_count} ({summ.user_turns} user / {summ.assistant_turns} assistant)",
            f"- **Context size:** ~{summ.context_tokens} tokens",
            f"- **Model:** {summ.model or 'n/a'}    **Git branch:** {summ.git_branch or 'n/a'}",
            "",
            f"**First prompt:** {summ.first_prompt or '(none)'}",
            "",
            f"**Last prompt:** {summ.last_prompt or '(none)'}",
            "",
        ]

        out = safe_join(Path(cwd), ".agents", "rules", f"session_{short}.md")
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text("\n".join(body), encoding="utf-8")
        return out

    def delete_session(self, project: str, session_id: str, hard: bool = False) -> dict[str, Any]:
        """Delete an AGY session.

        Soft (default): the session's conversation_summaries row is first saved
        as conversation_summary.json in .cc_mgr_trash/<id>.<stamp>/ — if that
        backup can't be made, nothing is touched — then brain/<id>,
        conversations/<id>.* and annotations/<id>.* move there too, and the row
        is removed from the DB, so everything can be restored.
        Hard: the same items are deleted outright.
        A failure to remove the DB row (e.g. agy holding a lock) is reported in
        `warnings`, never swallowed.
        """
        if not is_safe_id(session_id):
            raise ValueError("invalid session id")
        home = self._home()
        brain_dir = safe_join(home / "brain", session_id)
        if not brain_dir.is_dir():  # only real sessions can be deleted
            raise FileNotFoundError(f"session {session_id} not found")
        summaries = home / "conversation_summaries.db"
        if summaries.exists() and not resolves_inside(summaries, home):
            raise ValueError("conversation_summaries.db resolves outside the agy home; "
                             "refusing to modify it")

        def owned_files(dirname: str) -> list[Path]:
            d = home / dirname
            # Exact-name match, never a glob built from the request.
            return ([f for f in d.iterdir() if f.is_file() and f.name.startswith(session_id + ".")]
                    if d.is_dir() else [])

        files = owned_files("conversations") + owned_files("annotations")
        moved: list[str] = []
        warnings: list[str] = []
        trash: Path | None = None

        if hard:
            shutil.rmtree(brain_dir)
            moved.append(str(brain_dir))
            for f in files:
                f.unlink()
                moved.append(str(f))
        else:
            row = self._summary_row(home, session_id)  # raises: then nothing is touched
            stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
            trash = home / ".cc_mgr_trash" / f"{session_id}.{stamp}"
            trash.mkdir(parents=True, exist_ok=True)
            if row is not None:
                (trash / "conversation_summary.json").write_text(
                    json.dumps(row, ensure_ascii=False, indent=2), encoding="utf-8")
            shutil.move(str(brain_dir), str(trash / "brain"))
            moved.append(str(brain_dir))
            for f in files:
                (trash / f.parent.name).mkdir(exist_ok=True)
                shutil.move(str(f), str(trash / f.parent.name / f.name))
                moved.append(str(f))

        db_file = home / "conversation_summaries.db"
        if db_file.is_file():
            try:
                conn = sqlite3.connect(db_file, timeout=5.0)
                try:
                    conn.execute("DELETE FROM conversation_summaries WHERE conversation_id = ?",
                                 (session_id,))
                    conn.commit()
                finally:
                    conn.close()
            except sqlite3.Error as e:
                warnings.append(f"could not remove the session from conversation_summaries.db: {e}")

        _scan_cache.pop(str(home), None)
        result: dict[str, Any] = {"deleted": moved, "trash": str(trash) if trash else None}
        if warnings:
            result["warnings"] = warnings
        return result

    @staticmethod
    def _summary_row(home: Path, session_id: str) -> dict[str, Any] | None:
        """The session's conversation_summaries row as JSON-safe data (BLOBs
        base64); None if there is no DB or no row. Raises RuntimeError when the
        DB can't be read, so a soft delete never drops a row it didn't back up."""
        db_file = home / "conversation_summaries.db"
        if not db_file.is_file():
            return None
        try:
            conn = connect_sqlite_ro(db_file)
            try:
                row = conn.execute("SELECT * FROM conversation_summaries WHERE conversation_id = ?",
                                   (session_id,)).fetchone()
            finally:
                conn.close()
        except sqlite3.Error as e:
            raise RuntimeError(f"could not back up the session's conversation_summaries row "
                               f"({e}); nothing was deleted") from e
        if row is None:
            return None
        return {k: ({"base64": base64.b64encode(v).decode("ascii")} if isinstance(v, bytes) else v)
                for k, v in dict(row).items()}
